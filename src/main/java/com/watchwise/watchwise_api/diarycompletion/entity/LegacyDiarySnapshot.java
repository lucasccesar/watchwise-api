package com.watchwise.watchwise_api.diarycompletion.entity;

import com.watchwise.watchwise_api.content.entity.ContentType;
import jakarta.persistence.*;
import lombok.*;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.UUID;

@Entity
@Table(name = "legacy_diary_snapshots")
@Getter @Builder @NoArgsConstructor(access = AccessLevel.PROTECTED) @AllArgsConstructor
public class LegacyDiarySnapshot {
    @Id @GeneratedValue(strategy = GenerationType.UUID) private UUID id;
    @Column(name = "old_diary_entry_id", nullable = false) private UUID oldDiaryEntryId;
    @Column(name = "user_id", nullable = false) private UUID userId;
    @Column(name = "original_content_id", nullable = false) private UUID originalContentId;
    @Enumerated(EnumType.STRING) @Column(name = "original_content_type", nullable = false) private ContentType originalContentType;
    private Integer score;
    @Column(columnDefinition = "TEXT") private String comment;
    @Column(name = "watched_date") private LocalDate watchedDate;
    @Column(name = "watched_at") private Instant watchedAt;
    @Column(name = "watch_number") private Integer watchNumber;
    @Column(name = "watched_in_theater") private Boolean watchedInTheater;
    @Column(name = "auto_generated", nullable = false) private Boolean autoGenerated;
    @Column(name = "ignored", nullable = false) private Boolean ignored;
    @Column(name = "created_at", nullable = false) private LocalDateTime createdAt;
    @Column(name = "updated_at", nullable = false) private LocalDateTime updatedAt;
    @Column(name = "companions_json", columnDefinition = "TEXT") private String companionsJson;
    @Column(name = "flags_json", columnDefinition = "TEXT") private String flagsJson;
    @Version private Long version;
}
